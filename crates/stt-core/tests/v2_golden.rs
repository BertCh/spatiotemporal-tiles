//! Golden byte-stability pin for the **manifest formatVersion 3** writer — the
//! CURRENT DEFAULT emission (design notes:
//! `docs/roadmap/stt-packed-format-decisions.md`).
//!
//! THE CONTRACT: formatVersion 3 is the ONLY emission `stt-build` writes, so it
//! is what every published archive, every content-addressed pack name, and
//! every edge cache key is built on. This file pins it with a committed fixture
//! corpus under `tests/fixtures/v2-golden/` that the current writer MUST keep
//! reproducing byte-for-byte — every object AND the manifest (whose
//! formatVersion-3 `schemas` template table is part of the pin).
//!
//! Why a BYTE pin when formatVersion 3 is not frozen: the other coverage is
//! *decode-equivalence* (`packages/core/test/fixtures/v2-golden*`, generated by
//! `packages/core/scripts/make-v2-golden.sh`, asserted by the TS reader) and
//! *rebuild-determinism* (`reproducible_build.rs`
//! `v2_dataset_rebuild_is_byte_identical_including_schemas`, which compares two
//! builds of the SAME binary against each other). Neither notices an encoder
//! change that still decodes fine and is still self-consistent — a reordered
//! pack layout, a different zstd level, a dropped schema-metadata key, a
//! template-hoist tweak. Those silently re-address every object: identical
//! pixels, a wholly new pack fleet, and a cold cache on every deploy. Only a
//! committed corpus catches it, which is what this file is.
//!
//! formatVersion 3 is NOT frozen — an intentional format change is allowed. The pin's job is
//! to make such a change *deliberate and reviewed* (regenerate the fixture in
//! the same commit, and expect the diff to show every object address churning)
//! rather than accidental.
//!
//! Two datasets cover both directory container shapes the writer emits:
//!   * `single/` — whole-load v6 directory.
//!   * `paged/`  — root + leaf pages (`with_paging`).
//!
//! Tile content: a quantized point layer (coord quant + range-adaptive attr
//! quant → per-tile `stt:qa` / `stt:quant` metadata), a categorical property
//! (dictionary column), a trajectory layer with u16-delta `vertex_time`, and an
//! empty-bucket tile. All of it at the encoder defaults, so the compact time
//! shape (`TILE_META.st`/`et`) is exercised too — and the empty tile, which
//! keeps the absolute pair, is what mints the extra CORE template in
//! `manifest.schemas`. That per-tile-varying metadata is exactly what the
//! schema-template hoist must keep OUT of the shared `manifest.schemas`
//! entries — so the manifest bytes are the load-bearing part of this pin, not
//! an incidental one.
//!
//! # The corpus is built by TWO PASSES, because the encoder it pins has two
//!
//! Mechanism M2 makes the numeric affine, the dictionary-vs-`Utf8` verdict and
//! the integer leaf width functions of the DATASET rather than of whichever
//! rows a tile caught — carried into the encoder as
//! [`EncoderConfig::global_pins`]. A fixture built at `..EncoderConfig::default()`
//! leaves that field `None` and therefore encodes on the INCUMBENT per-tile
//! path: it would stay green through every byte the pinned path moves, and
//! regenerating it would re-bless unpinned bytes while pinning nothing new.
//! That is the failure this file has to avoid, so [`build_v2_dataset`] runs the
//! real shape in miniature — pass 1 derives [`golden_pins`] from the corpus's
//! own features, pass 2 encodes every tile against them — and
//! [`golden_fixture_exercises_the_pinned_path`] asserts, without reference to
//! any committed byte, that the pins actually BITE (a per-tile encode of the
//! same layer differs). If the corpus is ever shrunk or the pins unwired, that
//! test fails long before the byte pin could quietly go blind.
//!
//! The three pinned columns are chosen so each one changes something a per-tile
//! encoder would have decided differently:
//!   * `speed` (fractional) — the pinned affine is the DATASET's range, while
//!     every tile's own minimum differs, so `stt:qa` moves in every tile.
//!   * `count` (integer, dataset span > 16 bits) — pins to an `Int32` leaf,
//!     while each tile's own span fits `UInt16`. This is the §3.8 template fork
//!     made visible: one column, one realized PROPS shape.
//!   * `kind` (categorical) — pins to a dictionary against the dataset-global
//!     category list, which every tile ships IN FULL even though every tile
//!     holds a strict subset of it. The per-tile size comparison picks `Utf8`
//!     for tiles this small, so the pin flips the Arrow type outright.
//!
//! `expected-hashes.json` records the blake3-128 of every object so drift is
//! reported by name even when a byte-diff would be opaque.
//!
//! Regenerate (ONLY alongside an intentional, reviewed change to formatVersion-3
//! emission —
//! regenerating REPLACES the pin):
//!   cargo test -p stt-core --test v2_golden -- --ignored regenerate_v2_golden

