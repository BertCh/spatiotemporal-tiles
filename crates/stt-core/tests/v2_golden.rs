/// Category-count ceiling for a hoistable dictionary — mirrors
/// `stt_build::dataset_stats::MAX_HOISTED_CATEGORIES`.
const MAX_HOISTED_CATEGORIES: usize = 1024;
/// Category-UTF-8-byte ceiling — mirrors
/// `stt_build::dataset_stats::MAX_HOISTED_CATEGORY_BYTES`.
const MAX_HOISTED_CATEGORY_BYTES: u64 = 4096;

/// Resolve the dataset-global pins from the corpus's own features — pass 1 of
/// the two-pass build, in miniature.
///
/// This MIRRORS `stt_build::dataset_stats::DatasetStats::to_pins_with`, and is
/// repeated here for the same reason `required_capabilities` is repeated in
/// `examples/make-golden-fixture.rs`: the dependency runs `stt-build` →
/// `stt-core`, so a `stt-core` test cannot call the builder. The mirror is kept
/// THIN on purpose — every verdict below is delegated to the shared `stt-core`
/// functions the builder itself calls ([`AttrPinned::derive_auto`],
/// [`dataset_dictionary_is_smaller`]); only the ORDER of the categorical rule's
/// three tests and the two hoist caps are transcribed. If the builder's rule
/// changes, this must follow it, and the fixture's job is to make that a
/// reviewed byte movement rather than a silent one.
///
/// The one branch NOT transcribed is the distinct-set overflow
/// (`MAX_CATEGORIES = 65_536`): reproducing it would need a 65 K-category
/// fixture, and it resolves to the same `GlobalDictVerdict::Utf8` this function
/// already emits on the two size tests. It is covered by
/// `crates/stt-build/src/dataset_stats.rs`'s own unit tests.
fn golden_pins<'a>(layers: impl IntoIterator<Item = &'a ColumnarLayer>) -> GlobalColumnPins {
    let mut attr: BTreeMap<String, AttrPinned> = BTreeMap::new();
    let mut dict: BTreeMap<String, GlobalDictVerdict> = BTreeMap::new();

    // Numeric columns: the dataset's (min, max, max_abs, all_integer, finite).
    let mut numeric: BTreeMap<&str, (f64, f64, f64, bool, u64)> = BTreeMap::new();
    // Categorical columns: the first-seen global category list (the pinned
    // ordering rule, widened from per-tile to per-dataset), plus the wire-size
    // inputs. `Vec` + linear `contains`, never a `HashSet`: first-seen order is
    // part of the output and must not depend on hash iteration.
    let mut categorical: BTreeMap<&str, (Vec<String>, u64, u64)> = BTreeMap::new();

    for layer in layers {
        for (name, column) in &layer.properties {
            match column {
                PropertyColumn::Numeric(values) => {
                    let stats = numeric.entry(name.as_str()).or_insert((
                        f64::INFINITY,
                        f64::NEG_INFINITY,
                        0.0,
                        true,
                        0,
                    ));
                    for v in values.iter().flatten().copied().filter(|v| v.is_finite()) {
                        stats.0 = stats.0.min(v);
                        stats.1 = stats.1.max(v);
                        stats.2 = stats.2.max(v.abs());
                        stats.3 &= v.fract() == 0.0;
                        stats.4 += 1;
                    }
                }
                PropertyColumn::Categorical(values) => {
                    let stats = categorical
                        .entry(name.as_str())
                        .or_insert((Vec::new(), 0, 0));
                    for v in values.iter().flatten() {
                        if !stats.0.iter().any(|c| c == v) {
                            stats.0.push(v.clone());
                        }
                        stats.1 += 1;
                        stats.2 += v.len() as u64;
                    }
                }
                // Vector groups carry neither a scalar affine nor a dictionary
                // verdict, so `GlobalColumnPins` has no key for them and the
                // builder's pass-1 stats do not collect them either. The corpus
                // has none; the arm is explicit so adding one is a compile
                // error here rather than a silently unpinned column.
                PropertyColumn::Vector { .. } => {}
            }
        }
    }

    for (name, (min, max, max_abs, all_integer, finite)) in numeric {
        attr.insert(
            name.to_string(),
            AttrPinned::derive_auto(min, max, max_abs, all_integer, finite),
        );
    }
    for (name, (categories, values, total_value_bytes)) in categorical {
        let category_bytes: u64 = categories.iter().map(|c| c.len() as u64).sum();
        let k = categories.len();
        // Order matters and is the builder's: the wire test first (is the
        // dictionary the smaller form at DATASET scale, where the per-tile IPC
        // allowance is charged once rather than per tile?), then the resident
        // caps (is the hoisted list small enough to replicate into every tile
        // on the reader?).
        let verdict =
            if !dataset_dictionary_is_smaller(total_value_bytes, values, category_bytes, k as u64)
                || k > MAX_HOISTED_CATEGORIES
                || category_bytes > MAX_HOISTED_CATEGORY_BYTES
            {
                GlobalDictVerdict::Utf8
            } else {
                GlobalDictVerdict::Dictionary(Arc::new(categories))
            };
        dict.insert(name.to_string(), verdict);
    }
    GlobalColumnPins { attr, dict }
}

/// The dataset-global category list for `kind`, in the order the corpus first
/// presents them (tile seed 0 mints A and B, seed 1 mints C and D — see
/// [`TILE_KINDS`]). The pin ships THIS list, whole, in every tile.
///
/// The strings are long on purpose. The categorical verdict is a MEASUREMENT —
/// `dataset_dictionary_is_smaller` — and with three-letter categories over 16
/// cells the dictionary genuinely loses to plain `Utf8`, which would leave the
/// fixture pinning a verdict that changes nothing. At these lengths the
/// dictionary wins at dataset scale (371 B vs 576 B) while still LOSING the
/// per-tile comparison every tile makes today (279 B vs 154 B), so the pin
/// flips the Arrow type in every tile and the byte pin can see it.
/// [`golden_fixture_exercises_the_pinned_path`] asserts exactly that, so
/// shrinking the corpus below the crossover fails loudly instead of silently
/// re-blinding the fixture.
const KINDS: [&str; 4] = [
    "articulated-electric-transit-bus",
    "low-floor-light-rail-tram-vehicle",
    "harbour-passenger-ferry-vessel",
    "dockless-shared-electric-scooter",
];

/// Which two of [`KINDS`] each point tile uses. Every tile therefore holds a
/// STRICT SUBSET of the dataset-global list — the case a per-tile encoder gets
/// wrong (a tile-local dictionary per subset, one PROPS template each) and the
/// case TB-4's all-or-nothing hoist has to ship whole.
const TILE_KINDS: [[usize; 2]; 4] = [[0, 1], [2, 3], [0, 2], [1, 3]];

/// Quantized point layer: numeric `speed` (with a null), integer `count` (with
/// a null), and categorical `kind` (with a null). `seed` shifts ids/times/values
/// so distinct tiles get distinct `stt:qa` affines and `stt:time_offset_ms`
/// origins — and, for the pinned columns, so each tile's OWN verdict differs
/// from the dataset's.
fn point_layer(seed: u64, n: usize) -> ColumnarLayer {
    let base = 1_700_000_000_000i64 + seed as i64 * 3_600_000;
    let kinds = TILE_KINDS[(seed as usize) % TILE_KINDS.len()];
    ColumnarLayer {
        polygon_parts: None,
        name: "default".to_string(),
        feature_ids: (0..n as u64).map(|i| seed * 1000 + i).collect(),
        start_times: (0..n as i64).map(|i| base + i * 1000).collect(),
        end_times: (0..n as i64).map(|i| base + i * 1000 + 60_000).collect(),
        geometry: GeometryColumn::Point(
            (0..n)
                .map(|i| {
                    [
                        -122.4 + seed as f64 * 0.01 + i as f64 * 1e-4,
                        37.7 + i as f64 * 5e-5,
                    ]
                })
                .collect(),
        ),
        vertex_times: None,
        vertex_values: None,
        triangles: None,
        vertex_value_matrix: None,
        properties: vec![
            (
                "speed".to_string(),
                PropertyColumn::Numeric(
                    (0..n)
                        .map(|i| {
                            if i == 1 {
                                None
                            } else {
                                Some(seed as f64 * 7.5 + i as f64 * 3.25)
                            }
                        })
                        .collect(),
                ),
            ),
            // Integer column whose DATASET span (0..=90_003) overflows the
            // `UInt16` index space while every TILE's own span is 4. The pin
            // therefore lands on an `Int32` leaf everywhere, where a per-tile
            // encoder would pick `UInt16` in every one of these tiles — the
            // §3.8 leaf-width fork, made visible in the bytes.
            (
                "count".to_string(),
                PropertyColumn::Numeric(
                    (0..n)
                        .map(|i| {
                            if i == 4 {
                                None
                            } else {
                                Some((seed * 30_000 + i as u64) as f64)
                            }
                        })
                        .collect(),
                ),
            ),
            (
                "kind".to_string(),
                PropertyColumn::Categorical(
                    (0..n)
                        .map(|i| {
                            if i == 2 {
                                None
                            } else {
                                Some(KINDS[kinds[i % kinds.len()]].to_string())
                            }
                        })
                        .collect(),
                ),
            ),
        ],
    }
}

/// Trajectory layer with a tight per-vertex time span → the u16-delta
/// `vertex_time` encoding (per-layer origin/step in schema metadata).
fn trajectory_layer() -> ColumnarLayer {
    let base = 1_700_003_600_000i64;
    ColumnarLayer {
        polygon_parts: None,
        name: "tracks".to_string(),
        feature_ids: vec![9001, 9002],
        start_times: vec![base, base + 5_000],
        end_times: vec![base + 30_000, base + 42_000],
        geometry: GeometryColumn::LineString(vec![
            vec![[-122.40, 37.70], [-122.41, 37.71], [-122.42, 37.72]],
            vec![[-122.50, 37.75], [-122.51, 37.76]],
        ]),
        vertex_times: Some(vec![
            vec![base, base + 15_000, base + 30_000],
            vec![base + 5_000, base + 42_000],
        ]),
        vertex_values: None,
        triangles: None,
        vertex_value_matrix: None,
        properties: vec![(
            "speed".to_string(),
            PropertyColumn::Numeric(vec![Some(12.5), Some(30.0)]),
        )],
    }
}

/// Empty-bucket tile: zero rows, but the full column set (numeric +
/// categorical) — a dictionary column at n=0 still carries a DictionaryBatch.
///
/// Under the pins this tile is the sharpest case of all: with no rows there is
/// no tile-local evidence to decide anything from, so the incumbent encoder
/// degenerates (an all-null `UInt16` at `{o: 0, s: 1}`, and `Utf8` for the
/// categorical), while the pinned encoder emits the DATASET's affines and the
/// full dataset-global dictionary against zero keys. Same tile, and the whole
/// difference is which evidence the rule saw.
fn empty_layer() -> ColumnarLayer {
    ColumnarLayer {
        polygon_parts: None,
        name: "default".to_string(),
        feature_ids: vec![],
        start_times: vec![],
        end_times: vec![],
        geometry: GeometryColumn::Point(vec![]),
        vertex_times: None,
        vertex_values: None,
        triangles: None,
        vertex_value_matrix: None,
        properties: vec![
            ("speed".to_string(), PropertyColumn::Numeric(vec![])),
            ("count".to_string(), PropertyColumn::Numeric(vec![])),
            ("kind".to_string(), PropertyColumn::Categorical(vec![])),
        ],
    }
}

/// Temporal bucket the corpus is laid out on.
const BUCKET: i64 = 3_600_000;
/// Corpus time origin — the bucket floor of the 2023-11-14 base every layer
/// anchors at.
const T0: i64 = 1_700_000_000_000 - 1_700_000_000_000 % BUCKET;

/// The corpus as LAYERS, before any encoding — `(tile id, start, end, feature
/// count, layer)` in write order.
///
/// Split out so pass 1 and pass 2 read the SAME list, and so
/// [`golden_fixture_exercises_the_pinned_path`] can assert against the very
/// features the fixture is built from rather than a restatement of them. The
/// order is the encode order, which is what makes the derived dictionary's
/// first-seen ordering well defined.
fn corpus_layers() -> Vec<(TileId, i64, i64, u32, ColumnarLayer)> {
    let mut out: Vec<(TileId, i64, i64, u32, ColumnarLayer)> = Vec::new();
    // Quantized point tiles across a few cells/buckets (distinct qa/t0 per tile,
    // and — under the pins — a distinct strict subset of `KINDS` per tile).
    for k in 0..4u64 {
        let ts = T0 + (k as i64 % 2) * BUCKET;
        out.push((
            TileId::new(5, 5 + k as u32, 11, ts.max(0) as u64),
            ts,
            ts + BUCKET - 1,
            5,
            point_layer(k, 5),
        ));
    }
    // Trajectory tile (vertex_time u16-delta path).
    out.push((
        TileId::new(5, 9, 11, T0.max(0) as u64),
        T0,
        T0 + BUCKET - 1,
        2,
        trajectory_layer(),
    ));
    // Empty-bucket tile.
    out.push((
        TileId::new(5, 10, 11, (T0 + BUCKET).max(0) as u64),
        T0 + BUCKET,
        T0 + 2 * BUCKET - 1,
        0,
        empty_layer(),
    ));
    out
}

/// Build one golden dataset (single or paged directory) into `out`.
///
/// Everything is deterministic: fixed payload content, `SpatialMajor` ordering
/// (independent of the Auto heuristic), fixed pack target, default zstd level.
///
/// TWO PASSES, in the order the builder runs them:
///   1. [`corpus_layers`] → [`golden_pins`] — the dataset-global verdicts.
///   2. `encode_tile_with` against a config carrying those pins.
///
/// The writer is created FIRST because a layer frame references its schema
/// template by hash: the encoder needs the writer's collector before
/// the first `encode_tile_with` or the template never lands in `manifest.schemas`
/// and the archive decodes to nothing.
fn build_v2_dataset(out: &Path, paging: Option<usize>) -> stt_core::Manifest {
    let bucket = BUCKET;
    let t0 = T0;

    let mut writer = PackWriter::create(out, BlobOrdering::SpatialMajor, 4 * 1024)
        .unwrap()
        .with_paging(paging)
        .with_capabilities(vec![
            CAPABILITY_COORD_QUANT.to_string(),
            CAPABILITY_ATTR_QUANT.to_string(),
            // The encoder config below leaves `compact_times` at its default
            // (on), so these frames carry `TILE_META.st`/`et` — a shape a
            // reader must understand to reconstruct absolute times. Declaring
            // it keeps the fixture a CONFORMANT archive, matching what
            // `stt-build`'s `required_capabilities()` emits; a fixture that
            // used the shape without declaring it would pin a spec violation.
            CAPABILITY_TIME_DELTA.to_string(),
        ]);
    // The pin is on the DEFAULT emission — formatVersion 3 is not requested
    // here, it is what
    // an unconfigured writer produces. If the default ever moves, this fires
    // with a readable message instead of a wall of byte diffs.
    assert_eq!(stt_core::pack::PACKED_FORMAT_VERSION, 3);
    assert_eq!(stt_core::arrow_tile::LAYER_FRAME_VERSION, 2);

    let corpus = corpus_layers();
    // --- Pass 1 ---------------------------------------------------------
    let pins = Arc::new(golden_pins(corpus.iter().map(|(_, _, _, _, l)| l)));
    // A pin set that decided nothing would put the whole corpus back on the
    // incumbent per-tile path and leave this fixture blind to mechanism M2 —
    // the defect this shape exists to close. Assert the two verdicts that make
    // the corpus load-bearing, here rather than only in a test, so a
    // regeneration cannot mint a blind fixture even if run in isolation.
    assert!(
        matches!(
            pins.dict.get("kind"),
            Some(GlobalDictVerdict::Dictionary(_))
        ),
        "the corpus must be large enough that the dataset-global dictionary \
         verdict for `kind` is Dictionary — it is Utf8, so this fixture would \
         pin nothing new (see KINDS)"
    );
    assert_eq!(
        pins.attr.get("count").map(|p| p.leaf),
        Some(PinnedLeaf::I32),
        "the corpus must keep `count`'s dataset span above the UInt16 index \
         space, or the leaf-width pin is a no-op"
    );
    // --- Pass 2 ---------------------------------------------------------
    let cfg = golden_encoder_config(&writer, &pins);

    // (id, time_start, time_end, feature_count, payload)
    let tiles: Vec<(TileId, i64, i64, u32, Vec<u8>)> = corpus
        .iter()
        .map(|(id, ts, te, n, layer)| {
            let payload = encode_tile_with(std::slice::from_ref(layer), &cfg).unwrap();
            (*id, *ts, *te, *n, payload)
        })
        .collect();

    for (id, ts, te, n, payload) in &tiles {
        writer
            .add_tile_full(id, *ts, *te, Some(*ts), *n, Some(bucket as u64), payload)
            .unwrap();
    }
    let meta = Metadata::new("v2-golden")
        .with_description("Default formatVersion-3 byte-identity fixture")
        .with_zoom_levels(5, 5)
        .with_temporal_bucket_ms(bucket as u64)
        .with_time_range(stt_core::types::TimeRange::new(
            t0 as u64,
            (t0 + 2 * bucket - 1) as u64,
        ));
    writer.finalize(&meta).unwrap()
}

/// Recursively collect `relative path → file bytes` for a dataset directory.
fn collect_files(root: &Path) -> BTreeMap<String, Vec<u8>> {
    fn walk(root: &Path, dir: &Path, out: &mut BTreeMap<String, Vec<u8>>) {
        for entry in fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                walk(root, &path, out);
            } else {
                let rel = path
                    .strip_prefix(root)
                    .unwrap()
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy())
                    .collect::<Vec<_>>()
                    .join("/");
                out.insert(rel, fs::read(&path).unwrap());
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(root, root, &mut out);
    out
}

