// Read all metadata files
function loadMetadata() {
  const metadataFiles = fs
    .readdirSync(METADATA_DIR)
    .filter((f) => f.endsWith(".meta.json"));

  const metadata = {};
  for (const file of metadataFiles) {
    const datasetId = file.replace(".meta.json", "");
    const content = fs.readFileSync(path.join(METADATA_DIR, file), "utf8");
    metadata[datasetId] = JSON.parse(content);
  }

  return metadata;
}

// Generate datasets.ts content
function generateDatasetsFile(metadata) {
  const datasets = [];

  for (const [datasetId, meta] of Object.entries(metadata)) {
    const config = DATASET_CONFIGS[datasetId];
    if (!config) {
      console.warn(`Warning: No config template for dataset ${datasetId}`);
      continue;
    }

    const dataset = {
      ...config,
      url: `/data/${meta.filename}`,
      timeRange: {
        start: `Date.parse('${new Date(meta.timeRange.start).toISOString()}')`,
        end: `Date.parse('${new Date(meta.timeRange.end).toISOString()}')`,
      },
    };

    datasets.push(dataset);
  }

  // Generate TypeScript code
  let output = `/**
 * Dataset configurations for the spatiotemporal tiles showcase
 * 
 * AUTO-GENERATED by scripts/data-generation/generate-datasets-config.js
 * DO NOT EDIT MANUALLY - your changes will be overwritten!
 * 
 * To modify dataset configurations:
 * 1. Edit the DATASET_CONFIGS template in generate-datasets-config.js
 * 2. Rebuild the datasets with scripts/data-generation/generate-all.sh
 */

import { Dataset } from './types';

export const datasets: Dataset[] = [
`;

  for (const dataset of datasets) {
    output += `  {\n`;
    output += `    id: '${dataset.id}',\n`;
    output += `    name: '${dataset.name}',\n`;
    output += `    description: '${dataset.description}',\n`;
    output += `    url: '${dataset.url}',\n`;
    output += `    type: '${dataset.type}',\n`;
    output += `    timeRange: {\n`;
    output += `      start: ${dataset.timeRange.start},\n`;
    output += `      end: ${dataset.timeRange.end},\n`;
    output += `    },\n`;
    output += `    timeWindow: ${dataset.timeWindow},\n`;
    output += `    animationSpeed: ${dataset.animationSpeed},\n`;
    output += `    initialViewState: ${JSON.stringify(dataset.initialViewState, null, 6).replace(/\n/g, "\n    ")},\n`;

    if (dataset.legend) {
      output += `    legend: ${JSON.stringify(dataset.legend, null, 6).replace(/\n/g, "\n    ")},\n`;
    }

    output += `  },\n`;
  }

  output += `];\n`;
  output += `\n`;
  output += `export const DATASETS = datasets;

export function getDatasetById(id: string): Dataset | undefined {
  return datasets.find(d => d.id === id);
}

export const defaultDatasetId = 'earthquake-activity';\n`;

  return output;
}

// Main
